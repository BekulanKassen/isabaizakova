export const ui: Record<Lang, Record<UiKey, string>> = { kk, ru };

export function t(lang: Lang, key: UiKey, vars: Record<string, string | number> = {}): string {
  return ui[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export function isLang(x: unknown): x is Lang {
  return x === 'kk' || x === 'ru';
}

/** Same page in the other language: /ru/afisha/ → /kk/afisha/. */
export function altPath(pathname: string, to: Lang): string {
  const rest = pathname.replace(/^\/(kk|ru)(?=\/|$)/, '').replace(/^\/+/, '');
  return `/${to}/${rest}`.replace(/\/+$/, '') + '/';
}

